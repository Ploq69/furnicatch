// ==========================================
// Letter Pool — cycles through alphabet in random groups
// ==========================================

const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');

function shuffleArray(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function splitIntoGroups(letters, groupSizes) {
  const groups = [];
  let idx = 0;
  for (const size of groupSizes) {
    groups.push(letters.slice(idx, idx + size));
    idx += size;
  }
  return groups;
}

export class LetterPool {
  constructor() {
    this.cycleGroups = [];
    this.cycleIndex = 0;
    this.cycleComplete = false;
    this.spelledThisCycle = new Set();
    this.spelledThisLevel = new Set();
    this.currentKey = 'cycle';
    this.spelledByKey = new Map();
    this._generateCycle();
  }

  _generateCycle() {
    const shuffled = shuffleArray(ALPHABET);
    // 8 groups: two groups of 4, six groups of 3 = 26
    const groupSizes = [4, 3, 3, 3, 3, 3, 3, 4];
    // Shuffle the group sizes so the 4s appear in random positions
    const shuffledSizes = shuffleArray(groupSizes);
    this.cycleGroups = splitIntoGroups(shuffled, shuffledSizes);
    this.cycleIndex = 0;
    this.cycleComplete = false;
    this.spelledThisCycle.clear();
    this.spelledThisLevel.clear();
  }

  advanceLevel() {
    this.cycleIndex++;
    this.spelledThisLevel.clear();
    if (this.cycleIndex >= this.cycleGroups.length) {
      this._generateCycle();
    }
  }

  getCurrentLetters() {
    return this.cycleGroups[this.cycleIndex] || [];
  }

  setLetters(letters, key = 'default') {
    this.spelledByKey.set(this.currentKey, new Set(this.spelledThisLevel));
    this.currentKey = key;
    this.cycleGroups[this.cycleIndex] = letters.map(l => l.toUpperCase());
    this.spelledThisLevel = new Set(this.spelledByKey.get(this.currentKey) || []);
  }

  markSpelled(letter) {
    const upper = letter.toUpperCase();
    this.spelledThisCycle.add(upper);
    this.spelledThisLevel.add(upper);
    this.spelledByKey.set(this.currentKey, new Set(this.spelledThisLevel));
  }

  isSpelled(letter) {
    return this.spelledThisLevel.has(letter.toUpperCase());
  }

  allSpelledForLevel() {
    const current = this.getCurrentLetters();
    if (current.length === 0) return true;
    return current.every(l => this.spelledThisLevel.has(l));
  }

  getSpelledCount() {
    return this.spelledThisLevel.size;
  }

  getTotalForLevel() {
    return this.getCurrentLetters().length;
  }

  getProgressText() {
    const current = this.getCurrentLetters();
    if (current.length === 0) return '';
    return current.map(l => (this.spelledThisLevel.has(l) ? `${l}✓` : `${l}_`)).join(' ');
  }

  pickRandomLetter() {
    const current = this.getCurrentLetters();
    if (current.length === 0) return null;
    // Weight toward letters not yet spelled this level
    const unspelled = current.filter(l => !this.spelledThisLevel.has(l));
    const pool = unspelled.length > 0 ? unspelled : current;
    return pool[Math.floor(Math.random() * pool.length)];
  }

  pickWordForLetter(letter) {
    const list = SPELLING_WORDS[letter.toUpperCase()];
    if (!list || list.length === 0) return null;
    return list[Math.floor(Math.random() * list.length)];
  }

  reset() {
    this._generateCycle();
  }
}
